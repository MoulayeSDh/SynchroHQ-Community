  await a.locator("#app-language").selectOption("ar");
  await expect(a.locator("html")).toHaveAttribute("dir", "rtl");
  await width(a);
  await author.setOffline(true); await a.reload();
  await expect(a.getByText(correctionText, { exact: false })).toBeVisible();
  await a.locator("article.panel").filter({ has: a.locator(`a[href="/reports?report=${reportId}"]`) }).getByRole("button", { name: "إعداد التصحيح دون اتصال" }).click();
  await expect(a.getByLabel(/ملخص اليوم/)).toBeVisible();
