  await expect(draftButton).toBeVisible({ timeout: 30000 }); await draftButton.click();
  await a.getByLabel(/Report date/).fill(new Date().toISOString().slice(0,10));
  await a.getByLabel(/Situation level/).selectOption("0");
  await a.getByLabel(/Daily summary/).fill("Phase 7 shell report: complete author journey from the mobile English interface.");
  await a.getByRole("button", { name: /^Add —/ }).click();
