  await a.getByLabel(/Quantity/).fill("2");
  await a.getByLabel(/I confirm the accuracy/).check();
  console.log("author form prepared");
  await author.setOffline(true);
  await a.getByLabel("Add attachment").setInputFiles({ name: "preuve-phase7.pdf", mimeType: "application/pdf", buffer: evidence });
  await expect(a.getByText(/preuve-phase7.pdf/)).toBeVisible();
  await a.getByRole("button", { name: "Finalize report", exact: true }).click();
  await a.getByLabel("I have reviewed this report and confirm its content.").check();
  await a.getByRole("button", { name: "Confirm permanently", exact: true }).click();
  await expect(a.getByTestId("report-business-state")).toHaveText("Confirmed");
  await width(a);
  await a.screenshot({ path: path.resolve("../../.local/phase7-mobile.png"), fullPage: true });
  await author.setOffline(false);
  await expect(a.getByTestId("report-sync-state")).toHaveText("Report received by server", { timeout: 30000 });
  const originalHash = await a.getByTestId("report-hash").textContent();
  console.log("author report received");
  await b.goto(base);
  await b.locator('[data-account="reviewer"]').click();
  await nav(b,"Inbox");
  await expect(b.getByRole("heading", { name: /Rapport.*À examiner/ }).last()).toBeVisible({ timeout: 30000 });
  const row = b.locator("article.panel").filter({ hasText: "author_1" }).filter({ hasText: "À examiner" }).first();
  await row.getByRole("link", { name: "Consulter et commenter" }).click();
  await expect(b.locator(`main p[role="alert"]`)).toHaveCount(0);
  const fingerprint = b.locator("code").filter({ hasText: originalHash! });
  await expect(fingerprint).toBeVisible({ timeout: 30000 });
  await b.getByLabel("Commentaire", { exact: true }).fill("Phase 7 : revue depuis la tablette.");
  await b.getByRole("button", { name: "Ajouter le commentaire" }).click();
  await expect(b.getByText("Phase 7 : revue depuis la tablette.", { exact: true })).toBeVisible();
