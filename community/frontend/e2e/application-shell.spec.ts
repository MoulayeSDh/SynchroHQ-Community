  await expect(reviewedRow.getByRole("heading", { level: 2 })).toContainText("Confirmé");
  console.log("corrected report received and reviewed");
  await c.goto(base); await c.locator("#app-language").selectOption("en");
  await c.locator('[data-account="central"]').click();
  await nav(c,"Reports");
  await c.locator("aside.panel").getByRole("button").filter({ hasText: reportId.slice(0,8) }).click();
  await expect(c.locator("code").filter({ hasText: originalHash! })).toBeVisible();
  await expect(c.locator("code").filter({ hasText: correctedHash! })).toBeVisible();
  await expect(c.getByRole("button", { name: /Add comment|Request correction|Prepare new revision/ })).toHaveCount(0);
  await expect(c.getByRole("navigation").getByRole("link", { name: /Collection|Forms|Administration/ })).toHaveCount(0);
